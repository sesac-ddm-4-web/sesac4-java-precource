public class P01_Division {
    public static void main(String[] args) {
        System.out.println(7 / 2);
        System.out.println(7 % 2);
        System.out.println(7.0 / 2);
        System.out.println((double) 7 / 2);
        System.out.println(1 + 2 + "3");
        System.out.println("1" + 2 + 3);
    }
}
