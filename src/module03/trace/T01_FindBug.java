package module03.trace;

/*
 * [버그 찾기 T01] 끝나지 않는 프로그램
 *
 * 목표: 1부터 100까지의 '짝수'를 모두 더해서 2550을 출력하는 프로그램입니다.
 *       그런데 실행하면 영원히 끝나지 않습니다.
 *
 * 주의: 실행하면 멈추지 않는 것이 정상입니다.
 *   IntelliJ 하단의 빨간 네모(정지) 버튼으로 직접 꺼주세요. 그것도 좋은 경험입니다.
 *
 * 미션:
 *   1) 실행하지 말고 코드만 읽으면서 왜 끝나지 않는지 찾아보세요.
 *      (힌트: n이 1일 때 무슨 일이 일어나는지 한 줄씩 따라가 보세요)
 *   2) 코드를 고쳐서 2550이 출력되게 만드세요.
 *
 * 내가 찾은 원인:
 *
 */
public class T01_FindBug {
    public static void main(String[] args) {
        int sum = 0;
        int n = 1;

        while (n <= 100) {
            if (n % 2 == 0) {
                sum += n;
                n++;
            }
        }

        System.out.println(sum); // 2550이 나와야 합니다
    }
}
